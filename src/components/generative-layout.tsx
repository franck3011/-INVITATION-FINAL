function getDesignIndex(template: { id: string; category: string }): number {
  const idx = DESIGN_MAP[template.id];
  if (idx !== undefined && idx < DESIGNS.length) return idx;
  return simpleHash(template.id, DESIGNS.length);
}

export function GenerativeLayout(props: GenerativeProps) {
  let idx = getDesignIndex(props.template);
  if (
    props.themeOverrides?.layoutOverride !== undefined &&
    props.themeOverrides?.layoutOverride !== null &&
    props.themeOverrides?.layoutOverride !== "auto"
  ) {
    const forced = parseInt(props.themeOverrides.layoutOverride, 10);
    if (!isNaN(forced) && forced >= 0 && forced < DESIGNS.length) {
      idx = forced;
    }
  }
  const Component = DESIGNS[idx];
  return <Component {...props} />;
}

export function deriveParams(id: string) {
  return { designIndex: simpleHash(id, DESIGNS.length) };
}
